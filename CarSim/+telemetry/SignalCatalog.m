classdef SignalCatalog
    %SIGNALCATALOG Single source of truth for the recorded columns (SI units).
    %   Column order = order of the row built in Simulator.advance.
    %   Wheel order: FL, FR, RL, RR.
    methods (Static)
        function n = names()
            w = telemetry.SignalCatalog.wheels();
            n = [ ...
                "t", "lap", "lapTime", ...
                "x", "y", "s", "lateralOffset", ...
                "yaw", "yawRate", "speed", "ax", "ay", ...
                "steerAngle", "driveForceCmd", "driveForce", "brakeForce", ...
                "motorTorque", "wheelTorque", ...
                "Fx_" + w, "Fy_" + w, "Fz_" + w];
        end

        function u = units()
            u = [ ...
                "s", "-", "s", ...
                "m", "m", "m", "m", ...
                "rad", "rad/s", "m/s", "m/s^2", "m/s^2", ...
                "rad", "N", "N", "N", ...
                "N*m", "N*m", ...
                repmat("N", 1, 12)];
        end

        function k = count()
            k = numel(telemetry.SignalCatalog.names());
        end

        function w = wheels()
            w = ["FL", "FR", "RL", "RR"];
        end
    end
end
